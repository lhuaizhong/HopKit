import fs from 'node:fs/promises'
import path from 'node:path'
import assert from 'node:assert/strict'
import {createRequire} from 'node:module'
import {createServer} from 'vite'
const require=createRequire(import.meta.url)
const {chromium}=require(process.env.HOPKIT_PLAYWRIGHT??'C:/Users/lhz/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const out=path.resolve('test-output');await fs.mkdir(out,{recursive:true})
const server=await createServer({server:{host:'127.0.0.1',port:1420,strictPort:true}})
await server.listen()
const browser=await chromium.launch({headless:true,executablePath:process.env.HOPKIT_BROWSER??'C:/Users/lhz/AppData/Local/ms-playwright/chromium-1223/chrome-win64/chrome.exe'})
const page=await browser.newPage({viewport:{width:1440,height:1100}})
const errors=[];page.on('pageerror',e=>errors.push(String(e)))
try{
 await page.goto('http://127.0.0.1:1420/scripts/monitor-ui-fixture.html')
 await page.locator('.nav-item').filter({hasText:'Monitor'}).click()
 for(let i=0;i<3;i++)await page.locator('#monitor-target-'+i).fill('127.0.0.1')
 await page.getByRole('button',{name:'开始监测',exact:false}).click()
 await page.waitForSelector('.monitor-track')
 assert.equal(await page.locator('.monitor-chart').count(),3)
 assert.equal(await page.locator('.monitor-table tbody tr').count(),3)
 await page.getByRole('button',{name:'暂停监测',exact:true}).click()
 await page.getByRole('button',{name:'继续监测',exact:true}).waitFor()
 await page.locator('#monitor-note').fill('<script>unsafe</script>现场备注')
 await page.getByRole('button',{name:'添加事件',exact:true}).click()
 await page.getByText('<script>unsafe</script>现场备注',{exact:true}).waitFor()
 assert.equal(await page.evaluate(()=>globalThis.unsafe),undefined)
 await page.getByRole('button',{name:'继续监测',exact:true}).click()
 await page.getByRole('button',{name:'暂停监测',exact:true}).waitFor()
 await page.getByRole('button',{name:'全程',exact:true}).click()
 await page.screenshot({path:path.join(out,'monitor-ui.png'),fullPage:true})
 await page.getByRole('button',{name:'停止监测',exact:false}).click()
 await page.waitForFunction(()=>!document.querySelector('.monitor-actions'))
 await page.getByRole('button',{name:'导出 JSON',exact:true}).click()
 const exported=await page.evaluate(()=>JSON.parse(document.body.dataset.exported))
 assert.equal(exported.task.result.status,'cancelled');assert(exported.task.result.data.sample_count>0)
 await page.getByRole('button',{name:'English',exact:true}).click()
 assert((await page.locator('.monitor-results').innerText()).includes('Completed probes only'))
 await page.getByRole('button',{name:'Export image',exact:true}).click()
 await page.waitForFunction(()=>!!document.body.dataset.png,null,{timeout:20000}).catch(async e=>{throw new Error(String(e)+' '+await page.locator('.result-error').allTextContents())})
 const png=await page.evaluate(()=>document.body.dataset.png)
 await fs.writeFile(path.join(out,'monitor-export.png'),Buffer.from(png,'base64'))
 assert.equal(errors.length,0,errors.join('\n'))
 await fs.writeFile(path.join(out,'monitor-ui.json'),JSON.stringify({status:'passed',tests:['three targets on common timeline','pause/resume','escaped notes','entire range and comparison','stop retains counters','JSON export','bilingual results','PNG export'],errors},null,2))
 console.log('Monitor UI passed')
}finally{await browser.close();await server.close()}
