import {fileURLToPath} from 'node:url'
import {chromium} from '@playwright/test'
import {createServer} from 'vite'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const tool=process.argv[2]??'ping',other=tool==='ping'?'tcping':'ping'
assert.ok(['ping','tcping'].includes(tool))
const enabled=`#${tool}-sound-enabled`,when=`#${tool}-sound-when`
const output=new URL(`../test-output/${tool}-sound/`,import.meta.url)
await fs.mkdir(output,{recursive:true})
const server=await createServer({cacheDir:'node_modules/.vite-ping-sound-test',server:{host:'127.0.0.1',port:27189,strictPort:false,watch:{ignored:['**/target/**','**/test-output/**']}},optimizeDeps:{entries:['scripts/ping-sound-ui-fixture.html']}})
await server.listen()
let browser
try{browser=await chromium.launch({headless:true,...(process.env.HOPKIT_TEST_BROWSER?{executablePath:process.env.HOPKIT_TEST_BROWSER}:{channel:'msedge'})})}catch(e){await server.close();throw e}
const page=await browser.newPage({viewport:{width:960,height:680},locale:'zh-CN'}),errors=[],checks=[]
page.on('pageerror',e=>errors.push(String(e)));page.setDefaultTimeout(10000)
const select=async id=>{await page.locator('#tool-search').fill(id);await page.locator('#tool-search').press('Enter')}
const toneCount=()=>page.evaluate(()=>window.pingSoundFixture.tones.length)
const push=async(id,ok,status)=>page.evaluate(({id,ok,status})=>window.pingSoundFixture.sample(id,ok,status),{id,ok,status})
const start=async()=>{await page.locator('form button.primary').click();return page.evaluate(()=>window.pingSoundFixture.tasks.at(-1).id)}
const waitTones=async n=>page.waitForFunction(n=>window.pingSoundFixture.tones.length===n,n)
try{
 await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/scripts/ping-sound-ui-fixture.html`)
 await select(tool)
 assert.equal(await page.locator(enabled).isChecked(),false)
 await page.getByLabel('持续探测，直至手动停止',{exact:true}).check()
 let id=await start();await push(id,false);await page.waitForTimeout(800);assert.equal(await toneCount(),0)
 const request=await page.evaluate(()=>window.pingSoundFixture.requests.at(-1))
 assert.equal(request.count,0);assert.equal('ping_sound_enabled' in request,false)
 await page.locator(enabled).check()
 assert.equal(await page.locator(when).inputValue(),'failure')
 await page.waitForTimeout(450);assert.equal(await toneCount(),0)
 await push(id,true);await page.waitForTimeout(450);assert.equal(await toneCount(),0)
 await push(id,false);await waitTones(1)
 await page.waitForTimeout(1200);assert.equal(await toneCount(),1)
 checks.push('Default off, failure-only alerts, muted samples not replayed, duplicate polling silent')
 await page.locator(when).selectOption('success')
 await push(id,false);await page.waitForTimeout(450);assert.equal(await toneCount(),1)
 await push(id,true);await waitTones(2)
 assert.equal(await page.evaluate(()=>window.pingSoundFixture.tones.at(-1).frequency),880)
 // A real AudioContext produces a nonzero waveform through the actual gain envelope.
 await page.waitForTimeout(1100)
 await page.getByRole('button',{name:'试听',exact:true}).click()
 await page.waitForFunction(()=>window.pingSoundFixture.amplitude()>0.02)
 await waitTones(3)
 checks.push('Success-only alerts and live mode changes; real Web Audio waveform and preview')
 await page.waitForTimeout(1100)
 await page.evaluate(id=>{for(let i=0;i<8;i++)window.pingSoundFixture.sample(id,true)},id)
 await waitTones(4);await page.waitForTimeout(450);assert.equal(await toneCount(),4)
 checks.push('Batched samples coalesce and alerts are rate limited')
 await page.waitForTimeout(1100)
 await select(other);assert.equal(await page.locator(enabled).count(),0)
 assert.equal(await page.locator(`#${other}-sound-enabled`).isChecked(),false)
 const tcp=await start();await push(tcp,true);await page.waitForTimeout(450);assert.equal(await toneCount(),4)
 await push(id,true);await waitTones(5)
 checks.push(`Running ${tool} still alerts in another tool; ${other} remains muted by default`)
 await select(tool);await page.locator(enabled).uncheck()
 await page.waitForTimeout(1100);await push(id,true);await page.waitForTimeout(500);assert.equal(await toneCount(),5)
 await page.locator(enabled).check()
 await page.waitForTimeout(500);assert.equal(await toneCount(),5)
 // Cancel the tracked Ping through the real task-center control.
 await page.getByRole('button',{name:'停止全部',exact:true}).click()
 await push(id,true);await page.waitForTimeout(1100);assert.equal(await toneCount(),5)
 checks.push('Toggling during a task is immediate and stop-all suppresses late samples')
 // Selecting history must not track old events or make a sound.
 await page.locator('.task-row').filter({hasText:tool==='ping'?'192.0.2.99':'192.0.2.98'}).locator('button').first().click()
 await page.waitForTimeout(500);assert.equal(await toneCount(),5)
 await page.waitForTimeout(350);await page.reload();await select(tool)
 assert.equal(await page.locator(enabled).isChecked(),true)
 assert.equal(await page.locator(when).inputValue(),'success')
 await page.waitForTimeout(500);assert.equal(await toneCount(),0)
 checks.push('Historical results and reload stay silent; settings persist')
 await page.screenshot({path:fileURLToPath(new URL(`${tool}-sound-960.png`,output)),fullPage:true})
 await page.getByRole('button',{name:'English',exact:true}).click()
 await page.getByRole('button',{name:'Easy to read',exact:true}).click()
 assert.equal(await page.getByLabel('Sound alerts',{exact:true}).isChecked(),true)
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
 await page.screenshot({path:fileURLToPath(new URL(`${tool}-sound-readable-en-960.png`,output)),fullPage:true})
 checks.push('Chinese/English and both appearances at 960×680')
 await page.evaluate(()=>{window.originalAudioContext=window.AudioContext;window.AudioContext=class {constructor(){throw Error('Audio output unavailable')}}})
 await page.getByRole('button',{name:'Test sound',exact:true}).click()
 await page.getByRole('status').filter({hasText:'Sound is unavailable'}).waitFor()
 id=await start();await push(id,true);await page.waitForTimeout(450)
 assert.equal(await toneCount(),0)
 await page.evaluate(()=>{window.AudioContext=window.originalAudioContext})
 await page.getByRole('button',{name:'Test sound',exact:true}).click();await waitTones(1)
 assert.equal(await page.getByRole('status').filter({hasText:'Sound is unavailable'}).count(),0)
 checks.push(`Audio output errors do not block ${tool} and preview can recover`)
 await page.waitForTimeout(1100)
 await page.locator(when).selectOption('failure')
 await push(id,false,'interrupted');await page.waitForTimeout(500);assert.equal(await toneCount(),1)
 await page.locator('form button.stop').click()
 await push(id,false);await page.waitForTimeout(500);assert.equal(await toneCount(),1)
 id=await start()
 await page.locator('.task-row').filter({has:page.getByRole('button',{name:'Stop',exact:true})}).getByRole('button',{name:'Stop',exact:true}).click()
 await push(id,false);await page.waitForTimeout(500);assert.equal(await toneCount(),1)
 checks.push('Interrupted samples stay silent; form stop and individual task stop discard late results')
 if(tool==='tcping'){
  // Both tools may run at once with independent settings; refusals count as TCP failures.
  const tcpId=await start()
  await push(tcpId,true,'connected');await page.waitForTimeout(1100);assert.equal(await toneCount(),1)
  await push(tcpId,false,'refused');await waitTones(2)
  await select('ping');assert.equal(await page.locator('#ping-sound-enabled').isChecked(),false)
  await page.locator('#ping-sound-enabled').check();await page.locator('#ping-sound-when').selectOption('success')
  const pingId=await start()
  await push(pingId,false);await page.waitForTimeout(500);assert.equal(await toneCount(),2)
  await push(pingId,true);await waitTones(3)
  await page.waitForTimeout(1100);await push(tcpId,false,'timeout');await waitTones(4)
  await select('tcping');assert.equal(await page.locator(when).inputValue(),'failure')
  await page.locator(enabled).uncheck();await page.waitForTimeout(1100)
  await push(tcpId,false,'refused');await page.waitForTimeout(500);assert.equal(await toneCount(),4)
  await push(pingId,true);await waitTones(5)
  await page.getByRole('button',{name:'Stop all',exact:true}).click()
  await push(tcpId,false);await push(pingId,true);await page.waitForTimeout(1100);assert.equal(await toneCount(),5)
  await page.locator(enabled).check();await page.waitForTimeout(350);await page.reload();await select('tcping')
  assert.equal(await page.locator(enabled).isChecked(),true);assert.equal(await page.locator(when).inputValue(),'failure')
  await select('ping');assert.equal(await page.locator('#ping-sound-enabled').isChecked(),true);assert.equal(await page.locator('#ping-sound-when').inputValue(),'success')
  assert.equal(await toneCount(),0)
  checks.push('TCP connected/refused/timeout outcomes; simultaneous Ping/TCPing alerts and settings stay independent across reloads')
 }
 assert.deepEqual(errors,[])
 await fs.writeFile(new URL('ui.json',output),JSON.stringify({status:'passed',checks,errors},null,2))
 console.log(checks)
}catch(error){await page.screenshot({path:fileURLToPath(new URL('failure.png',output)),fullPage:true});await fs.writeFile(new URL('failure.txt',output),String(error)+'\n'+await page.locator('body').innerText());throw error}finally{await browser.close();await server.close()}
